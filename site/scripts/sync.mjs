// Copies what the site shares with the app: the design tokens, the two fonts and
// the 3D icons it shows. Nothing is edited by hand, so the two never drift apart.
import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const site = join(here, "..");
const app = join(site, "..", "src");

const tokens = readFileSync(join(app, "styles", "tokens.css"), "utf8");
mkdirSync(join(site, "src", "styles"), { recursive: true });
// The app switches theme with [data-theme="dark"]. The site also follows the system
// when nobody chose, so the same dark block is repeated under a media query that
// a stored "light" choice (data-theme="light" on <html>) switches off.
const dark = tokens.match(/\[data-theme="dark"\]\s*\{([\s\S]*?)\n\}/);
if (!dark) throw new Error("tokens.css has no [data-theme=\"dark\"] block to follow");
const followSystem = `\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {${dark[1]}\n  }\n}\n`;
writeFileSync(
  join(site, "src", "styles", "app-tokens.css"),
  `/* Generated by scripts/sync.mjs from src/styles/tokens.css. Do not edit. */\n${tokens}${followSystem}`,
);

const fontDir = join(site, "src", "assets", "fonts");
mkdirSync(fontDir, { recursive: true });
for (const f of [
  "bricolage-grotesque-latin-wght-normal.woff2",
  "inter-latin-wght-normal.woff2",
  "LICENSE-Bricolage-OFL.txt",
  "LICENSE-Inter-OFL.txt",
]) {
  cpSync(join(app, "assets", "fonts", f), join(fontDir, f));
}

const iconDir = join(site, "src", "assets", "icons3d");
mkdirSync(iconDir, { recursive: true });
for (const f of ["piggy", "checklist", "coins", "safe", "phone"]) {
  cpSync(join(app, "assets", "icons3d", `${f}.png`), join(iconDir, `${f}.png`));
}
console.log("site: tokens, fonts and icons synced from the app");
