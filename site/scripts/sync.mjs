// Copies what the site shares with the app: the design tokens, and the fonts it uses. Nothing is edited by hand, so the two never drift apart.
import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const site = join(here, "..");
const app = join(site, "..", "src");

const tokens = readFileSync(join(app, "styles", "tokens.css"), "utf8");
mkdirSync(join(site, "src", "styles"), { recursive: true });
// The app switches theme with [data-theme="dark"]. The site always opens light
// (Layout.astro sets data-theme="light"), so it does not follow the system.
writeFileSync(
  join(site, "src", "styles", "app-tokens.css"),
  `/* Generated by scripts/sync.mjs from src/styles/tokens.css. Do not edit. */\n${tokens}`,
);

const fontDir = join(site, "src", "assets", "fonts");
mkdirSync(fontDir, { recursive: true });
for (const f of [
  "bricolage-grotesque-latin-wght-normal.woff2",
  "inter-latin-wght-normal.woff2",
  "gloria-hallelujah-latin-400-normal.woff2",
  "LICENSE-Bricolage-OFL.txt",
  "LICENSE-Inter-OFL.txt",
  "LICENSE-Gloria-OFL.txt",
]) {
  cpSync(join(app, "assets", "fonts", f), join(fontDir, f));
}

const iconDir = join(site, "src", "assets", "icons3d");
mkdirSync(iconDir, { recursive: true });
for (const f of ["piggy", "house", "coins", "safe", "checklist", "receipt", "chart-up", "shield", "gear", "badge", "plate", "car", "cart", "cinema", "bank", "wallet"]) {
  cpSync(join(app, "assets", "icons3d", `${f}.png`), join(iconDir, `${f}.png`));
}
// The site's plane is the redrawn one (right wings, with a suitcase), kept under the old name.
cpSync(join(app, "assets", "icons3d", "set2", "cat-travel.png"), join(iconDir, "plane.png"));
console.log("site: tokens, fonts and polaroid icons synced from the app");
